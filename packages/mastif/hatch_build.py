"""Hatch build hook: embed git information into the wheel as ``mastif/_build_info.py``.

Why: an installed wheel on a test station has no git checkout, yet every run should
record which commit produced it. At build time we know the commit, so we write it into
the package. `mastif.infra.version.GitInfo.embedded` reads it back.

Editable installs (``uv sync`` in development) are skipped on purpose. There the runtime
``git`` fallback gives live information, whereas an embedded file would freeze the
commit at the time of the last sync.

This file runs inside hatchling's isolated build environment, where mastif and its
dependencies are not installed, so it must use only the standard library. Org SDKs can
copy it as-is, changing ``PACKAGE``.
"""

import subprocess
import tempfile
from datetime import UTC, datetime
from pathlib import Path

from hatchling.builders.hooks.plugin.interface import BuildHookInterface  # ty: ignore[unresolved-import]

PACKAGE = "mastif"


def _git(root: str, *args: str) -> str | None:
    """Run one git command in ``root``; return stripped output or ``None`` on failure."""
    try:
        out = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout.strip() if out.returncode == 0 else None


def build_info(root: str) -> dict[str, object] | None:
    """Collect git information for the repository at ``root``, or ``None`` outside git."""
    log = _git(root, "log", "-1", "--format=%H%n%h%n%cI%n%an%n%s")
    if log is None:
        return None
    commit, short, date, author, subject = [*log.splitlines(), "", "", "", "", ""][:5]
    status = _git(root, "status", "--porcelain")
    return {
        "commit": commit or None,
        "short_commit": short or None,
        "commit_date": date or None,
        "author": author or None,
        "subject": subject or None,
        "branch": _git(root, "rev-parse", "--abbrev-ref", "HEAD"),
        "dirty": None if status is None else bool(status),
        "captured_at": datetime.now(UTC).isoformat(timespec="seconds"),
    }


class BuildInfoHook(BuildHookInterface):
    """Add ``<PACKAGE>/_build_info.py`` to a (non-editable) wheel.

    The file is written to a temporary directory and mapped into the wheel, so the source
    tree is never modified. A stale file in ``src/`` would otherwise shadow live git
    information in development.
    """

    def initialize(self, version: str, build_data: dict) -> None:
        """Hatch entry point; ``version`` is ``"editable"`` for editable installs."""
        if version == "editable":
            return
        info = build_info(self.root)
        if info is None:
            return
        target = Path(tempfile.mkdtemp(prefix="mastif-build-info-")) / "_build_info.py"
        target.write_text(
            f"# Generated by hatch_build.py at build time. Do not edit.\nBUILD_INFO = {info!r}\n",
            encoding="utf-8",
        )
        build_data.setdefault("force_include", {})[str(target)] = f"{PACKAGE}/_build_info.py"
